"""Build PK.COM and the MS-DOS 4.0 disk (docs/DESIGN.md).

    python3 -I tools/build_dos.py [--msdos4 PATH] [--roms PATH] [--with-roms]

PK.COM (src/dos/pk.asm) holds the game code with optional runtime FM
(--fm), and reads the user's ROM files at run time; it contains no ROM bytes,
no ROM-derived data and no ROM file names. The disk is a copy of the
FreeDOS-88VA project's MS-DOS 4.0 for the PC-88VA (MIT licence, release
msdos4-va.2, msdos4-pc88va-2hd.d88, checked by its SHA-256) keeping the
system files, the licence and the readme, plus PK.COM, PK.TXT, PKLICENS.TXT
and an AUTOEXEC.BAT that starts PK. Outputs, in build/ (ignored by git):

    build/dist/pk-msdos4.d88        the disk, without ROM files
    build/dist/PK.COM
    build/dist/PK.TXT               (docs/dist/PK.TXT)
    build/dist/PKLICENS.TXT         (LICENSE)
    build/dist/install_roms.py      adds the ROM files to a disk image
    build/dist/pcengine_disk.py     its FAT12 helper, from vaeg
    build/pk-msdos4-roms.d88        with --with-roms: the disk with the ROM
                                    files from --roms (private, for tests)

The zip is read only for the --with-roms disk.
"""

import argparse
import hashlib
import importlib.util
import shutil
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build  # noqa: E402,F401
import d88  # noqa: E402
import gfx  # noqa: E402
import patches  # noqa: E402

REPO = d88.REPO
VAEG_DISK_TOOL = REPO.parent / "vaeg" / "tools" / "pc88va" / "pcengine_disk.py"
MSDOS4_RELEASE = "https://github.com/FreeDOS-88VA/MS-DOS/releases/tag/msdos4-va.2"
MSDOS4_SHA256 = "7c4b141d31e0034120e0b07eb93b9bea808e1c54822e48e15189cc7398385db0"
MSDOS4_DEFAULT = Path.home() / ".cache/vaeg/msdos4-va.2/dl/msdos4-pc88va-2hd.d88"
FIXED_FAT_DATE = ((2026 - 1980) << 9) | (10 << 5) | 17     # 2026-10-17
AUTOEXEC = b"@ECHO OFF\r\nPATH A:\\\r\nPROMPT $P$G\r\nVER\r\nPK\r\n"


def load_disk_tool(path: Path = VAEG_DISK_TOOL):
    spec = importlib.util.spec_from_file_location("pcengine_disk", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.fat_now = lambda: (0, FIXED_FAT_DATE)
    return module


def levels() -> tuple[bytes, bytes]:
    """tools/gfx.py's colour levels for 3 and 2 resistor bits."""
    level3 = bytes(gfx._level(0x21 * (v & 1) + 0x47 * ((v >> 1) & 1) + 0x97 * ((v >> 2) & 1))
                   for v in range(8))
    level2 = bytes(gfx._level(0x51 * (v & 1) + 0xAE * ((v >> 1) & 1)) for v in range(4))
    return level3, level2


LOAD_SEG = 0x3000


def assemble(work: Path, maze_palette: bool = False, sgp_sprites: bool = False,
             scene_hold: bool = False, sgp_cache: bool = False, fm: bool = False) -> bytes:
    flags = ["-DMAZE_PALETTE"] if maze_palette else []
    if sgp_sprites or sgp_cache:
        flags.append("-DSGP_SPRITES")
    if sgp_cache:
        flags.append("-DSGP_CACHE")
    if scene_hold:
        flags.append("-DSCENE_HOLD")
    d88.nasm(["-I", f"{REPO}/", *flags, f"-DLOAD_SEG={LOAD_SEG:#x}", "-DDOS_FM" if fm else "-DNO_FM", "-o", str(work / "game.bin"),
              str(REPO / "src/game/pk.asm")])
    if len((work / "game.bin").read_bytes()) != build.CODE_BYTES:
        raise SystemExit("error: the game code is not 16 KiB")
    (work / "screen_offs.bin").write_bytes(gfx.tile_screen_offsets())
    level3, level2 = levels()
    sites = sorted(site for sites in patches._INPUT_READS.values() for site in sites)
    lines = [
        "; Generated by tools/build_dos.py",
        f"LOAD_SEG\tequ\t{LOAD_SEG:#x}",
        f'%define GAME_BIN "{work / "game.bin"}"',
        f'%define SCREEN_OFFS_BIN "{work / "screen_offs.bin"}"',
        "input_sites\tdw\t" + ", ".join(f"{s:04X}h" for s in sites) + ", 0",
        "level3\t\tdb\t" + ", ".join(f"{v}" for v in level3),
        "level2\t\tdb\t" + ", ".join(f"{v}" for v in level2),
        "b_patches\tdb\t" + ", ".join(f"{a & 255:#04x}, {a >> 8:#04x}, {v:#04x}"
                                       for a, v, _ in patches.B_PATCHES) + ", 0, 0",
        f"B_START_AT\tequ\t{patches.B_START[0]:#06x}",
        f"B_START_BYTES\tequ\t{len(patches.B_START[1])}",
        "b_start\t\tdb\t" + ", ".join(f"{v:#04x}" for v in patches.B_START[1]),
    ]
    (work / "dosdata.inc").write_text("\n".join(lines) + "\n", encoding="ascii")
    if fm:
        import fmdata
        (work / "fmtables.inc").write_text(fmdata.nasm_tables(), encoding="ascii")
    d88.nasm([*(["-DSGP_CACHE"] if sgp_cache else []), *(["-DDOS_FM"] if fm else []),
              "-I", f"{work}/", "-I", f"{REPO / 'src/dos'}/", "-o", str(work / "PK.COM"),
              str(REPO / "src/dos/pk.asm")])
    return (work / "PK.COM").read_bytes()


def make_disk(tool, msdos4: Path, files: dict[str, bytes], output: Path) -> None:
    with tempfile.TemporaryDirectory(prefix="pk-dos-") as tmp:
        work = Path(tmp)
        vanilla = work / "vanilla.d88"
        tool.create_vanilla(str(msdos4), str(vanilla))
        disk = tool.PcEngineDisk(vanilla.read_bytes(), require_system_files=False)
        for name, contents in files.items():
            path = work / name
            path.write_bytes(contents)
            tool.add_file(disk, disk.root, path)
        disk.flush()
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes(disk.image)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--msdos4", type=Path, default=MSDOS4_DEFAULT,
                        help=f"msdos4-pc88va-2hd.d88 of {MSDOS4_RELEASE}")
    parser.add_argument("--roms", type=Path, default=patches.DEFAULT_ZIP,
                        help="zip or directory with the ROM files (default: $PK_ROMS)")
    parser.add_argument("--with-roms", action="store_true")
    parser.add_argument("--fm", action="store_true", help="enable runtime FM cache loading and quick fallback")
    parser.add_argument("--maze-palette", action="store_true",
                        help="experimental dedicated wall palette (hardware gate pending)")
    parser.add_argument("--sgp-cache", action="store_true", help="cache expanded SGP sprites in 24 KiB RAM")
    parser.add_argument("--scene-hold", action="store_true",
                        help="complete bulk background updates before changing the display page")
    parser.add_argument("--sgp-sprites", action="store_true",
                        help="experimental SGP transparent sprite copies; CPU erase retained")
    parser.add_argument("--output-dir", type=Path, default=REPO / "build",
                        help="output root; use a separate directory for each release or experiment")
    args = parser.parse_args()
    if hashlib.sha256(args.msdos4.read_bytes()).hexdigest() != MSDOS4_SHA256:
        raise SystemExit(f"error: {args.msdos4} is not msdos4-pc88va-2hd.d88 of {MSDOS4_RELEASE}")
    tool = load_disk_tool()
    dist = args.output_dir / "dist"
    dist.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="pk-dos-") as tmp:
        com = assemble(Path(tmp), maze_palette=args.maze_palette,
                       sgp_sprites=args.sgp_sprites, scene_hold=args.scene_hold,
                       sgp_cache=args.sgp_cache, fm=args.fm)

    def text(path: Path) -> bytes:
        return path.read_bytes().replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")

    files = {"PK.COM": com, "PK.TXT": text(REPO / "docs/dist/PK.TXT"),
             "PKLICENS.TXT": text(REPO / "LICENSE"), "AUTOEXEC.BAT": AUTOEXEC}
    make_disk(tool, args.msdos4, files, dist / "pk-msdos4.d88")
    for name in ("PK.COM", "PK.TXT", "PKLICENS.TXT"):
        (dist / name).write_bytes(files[name])
    shutil.copyfile(REPO / "README.md", dist / "README.md")
    shutil.copyfile(REPO / "tools/install_roms.py", dist / "install_roms.py")
    shutil.copyfile(VAEG_DISK_TOOL, dist / "pcengine_disk.py")
    for name in ("fmdata.py", "fmfit.py"):
        shutil.copyfile(REPO / "tools" / name, dist / name)
    print(f"{dist / 'pk-msdos4.d88'}: MS-DOS 4.0 and PK.COM ({len(com)} bytes)")
    if args.with_roms:
        import install_roms
        roms = install_roms.read_roms(args.roms)
        for name, data in roms.items():
            files[name] = data
        output = args.output_dir / "pk-msdos4-roms.d88"
        make_disk(tool, args.msdos4, files, output)
        print(f"{output}: with the ROM files (private)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
